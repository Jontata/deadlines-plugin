export function renderHtml(template, css, logic, app) {
  const replacements = {
    STYLES: `<style id="deadlines-styles">\n${css.replace(/<\/style/gi, '<\\/style')}\n</style>`,
    LOGIC: `<script>\n// <logic> Pure functions, no DOM.\n${logic.replace(/<\/script/gi, '<\\/script')}\n// </logic>\n</script>`,
    APP: `<script>\n${app.replace(/<\/script/gi, '<\\/script')}\n</script>`,
  };
  const html = Object.entries(replacements).reduce((html, [key, value]) => {
    const marker = `<!-- ${key} -->`;
    if (html.split(marker).length !== 2) throw new Error(`Expected one ${marker} placeholder`);
    return html.replace(marker, () => value);
  }, template);
  return html.replace(/<!doctype html>/i, (doctype) => `${doctype}\n${generatedMarker}`);
}

function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  return (crc ^ 0xffffffff) >>> 0;
}

// Fixed filenames make a small native ZIP writer sufficient; no archive dependency.
export function createZip(entries) {
  const records = entries.reduce((state, { name, data }) => {
    if (!/^[\w.-]+$/.test(name)) throw new Error(`Unsafe archive filename: ${name}`);
    const filename = Buffer.from(name);
    const bytes = Buffer.isBuffer(data) ? data : Buffer.from(data);
    const packed = deflateRawSync(bytes);
    const header = Buffer.alloc(30);
    header.writeUInt32LE(0x04034b50, 0);
    header.writeUInt16LE(20, 4);
    header.writeUInt16LE(8, 8);
    header.writeUInt16LE(0x21, 12); // 1980-01-01, deterministic output.
    header.writeUInt32LE(crc32(bytes), 14);
    header.writeUInt32LE(packed.length, 18);
    header.writeUInt32LE(bytes.length, 22);
    header.writeUInt16LE(filename.length, 26);
    const record = Buffer.concat([header, filename, packed]);
    const directory = Buffer.alloc(46);
    directory.writeUInt32LE(0x02014b50, 0);
    directory.writeUInt16LE(20, 4);
    directory.writeUInt16LE(20, 6);
    header.copy(directory, 8, 6, 28);
    directory.writeUInt32LE(state.offset, 42);
    return {
      files: [...state.files, record],
      directory: [...state.directory, directory, filename],
      offset: state.offset + record.length,
    };
  }, { files: [], directory: [], offset: 0 });
  const directory = Buffer.concat(records.directory);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(records.offset, 16);
  return Buffer.concat([...records.files, directory, end]);
}

async function thirdPartyNotices() {
  const lock = JSON.parse(await read('package-lock.json'));
  const packages = Object.entries(lock.packages).filter(([path, info]) => path && !info.dev && !info.optional);
  const notices = await Promise.all(packages.map(async ([path]) => {
    const packageRoot = join(root, path);
    const info = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8'));
    const files = (await readdir(packageRoot)).filter((name) => /^(licen[sc]e|copying|copyright|notice)(\.|$)/i.test(name));
    const licenses = await Promise.all(files.map(async (name) => {
      const path = join(packageRoot, name);
      return (await stat(path)).isFile() ? readFile(path, 'utf8') : '';
    }));
    return `${info.name} ${info.version}\nLicense: ${info.license || 'See included license text'}\n${licenses.filter(Boolean).join('\n\n')}`;
  }));
  return `Third-party software bundled with the Deadlines plugin\n\n${[...notices, coreJsNotice].join('\n\n' + '='.repeat(72) + '\n\n')}\n`;
}

async function bundleBrowser(entryPoint) {
  const bundle = await build({
    absWorkingDir: root,
    entryPoints: [entryPoint],
    outfile: 'bundle.js',
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'inline',
    loader: { '.svg': 'dataurl', '.png': 'dataurl', '.woff': 'dataurl', '.woff2': 'dataurl' },
  });
  const js = bundle.outputFiles.find((file) => file.path.endsWith('.js'))?.text;
  if (!js) throw new Error(`${entryPoint} did not produce JavaScript`);
  const css = bundle.outputFiles.filter((file) => file.path.endsWith('.css')).map((file) => file.text).join('\n');
  if (/url\(\s*["']?(?:https?:|\/\/)/i.test(css)) throw new Error('Styles must not depend on external assets');
  return { css, js };
}

export function renderHostPlugin(assets) {
  return `// Generated by build.mjs. Static browser assets; no host-side app execution.\n` +
    `(function () {\n` +
    `  if (typeof PluginAPI === 'undefined' || typeof PluginAPI.onMessage !== 'function') {\n` +
    `    throw new Error('Deadlines requires Super Productivity plugin message support.');\n` +
    `  }\n` +
    `  const assets = ${JSON.stringify(assets)};\n` +
    `  PluginAPI.onMessage(function (message) {\n` +
    `    if (!message || typeof message !== 'object' || Array.isArray(message) || message.type !== 'deadlines-assets-v1') {\n` +
    `      throw new Error('Unsupported Deadlines asset request.');\n` +
    `    }\n` +
    `    return assets;\n` +
    `  });\n` +
    `})();\n`;
}

export function assertSizeLimits(html, plugin, zip) {
  const limits = [
    ['index.html', html, 100 * 1024],
    ['plugin.js', plugin, 5 * 1024 * 1024],
    ['Plugin ZIP', zip, 10 * 1024 * 1024],
  ];
  for (const [name, data, limit] of limits) {
    if (data === undefined) continue;
    const size = Buffer.byteLength(data);
    if (size > limit) throw new Error(`${name} is ${size} bytes; Super Productivity allows at most ${limit} bytes.`);
  }
}

export async function buildPlugin() {
  const [template, styles, logic, manifestText, assets, bootstrap, notices, license] = await Promise.all([
    read('src/index.html'), read('src/style.css'), read('src/logic.js'), read('manifest.json'),
    bundleBrowser('src/app.js'), bundleBrowser('src/bootstrap.js'), thirdPartyNotices(), read('LICENSE'),
  ]);
  const html = renderHtml(template, styles, logic, bootstrap.js);
  if (/<script\b[^>]*\bsrc\s*=/i.test(html)) throw new Error('The plugin must not load external scripts');
  const plugin = renderHostPlugin(assets);
  assertSizeLimits(html, plugin);
  const manifest = JSON.parse(manifestText);
  if (!/^[\d.]+$/.test(manifest.version)) throw new Error('Invalid plugin version');
  const zipPath = join(root, `deadlines-plugin-${manifest.version}.zip`);
  const entries = [
    { name: 'manifest.json', data: manifestText },
    { name: 'index.html', data: html },
    { name: 'plugin.js', data: plugin },
    { name: 'icon.svg', data: await read('icon.svg') },
    { name: 'LICENSE', data: license },
    { name: 'THIRD-PARTY-NOTICES.txt', data: notices },
  ];
  const zip = createZip(entries);
  assertSizeLimits(html, plugin, zip);
  await writeFile(join(root, 'index.html'), html);
  await writeFile(join(root, 'plugin.js'), plugin);
  await writeFile(join(root, 'THIRD-PARTY-NOTICES.txt'), notices);
  await writeFile(zipPath, zip);
  console.log(`Built index.html (${Buffer.byteLength(html)} bytes), plugin.js (${Buffer.byteLength(plugin)} bytes), ZIP (${zip.length} bytes): ${zipPath}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildPlugin();
}
